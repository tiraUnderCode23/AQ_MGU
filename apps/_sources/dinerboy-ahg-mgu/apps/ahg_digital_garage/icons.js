'use strict';
/** icons.js - line icons on a 24 x 24 grid, drawn at any size (nav, cards, tiles). */
function icon(cv,id,x,y,size,c){
    const s=size/24,w=Math.max(1.4,1.8*s);
    const P=(pts)=>cv.polyline(pts.map((p)=>[x+p[0]*s,y+p[1]*s]),w,c);
    const ring=(cx,cy,r)=>cv.arc(x+cx*s,y+cy*s,Math.max(0,r*s-w/2),r*s+w/2,0,360,c);
    const dot=(cx,cy,r)=>cv.circle(x+cx*s,y+cy*s,r*s,c);
    switch(id){
    case 'garage':P([[2,10],[12,3],[22,10]]);P([[4,9],[4,21]]);P([[20,9],[20,21]]);P([[7,17],[7,14],[9,11],[15,11],[17,14],[17,17],[7,17]]);P([[8,17],[8,19]]);P([[16,17],[16,19]]);break;
    case 'service':P([[4,20],[13,11]]);ring(16,8,4.5);P([[14,4],[16,8],[20,6]]);break;
    case 'maintenance':P([[3,6],[21,6],[21,21],[3,21],[3,6]]);P([[3,10],[21,10]]);P([[8,3],[8,7]]);P([[16,3],[16,7]]);
        [[7,14],[12,14],[17,14],[7,18],[12,18]].forEach((p)=>dot(p[0],p[1],1.1));break;
    case 'diagnostics':P([[1,13],[6,13],[9,5],[13,20],[16,10],[18,13],[23,13]]);break;
    case 'modifications':ring(12,13,7);ring(12,13,2.5);P([[12,6],[12,2],[20,2]]);P([[5,13],[2,13]]);P([[17,8],[19,6]]);break;
    case 'records':P([[4,3],[18,3],[20,5],[20,21],[4,21],[4,3]]);P([[8,9],[16,9]]);P([[8,13],[16,13]]);P([[8,17],[13,17]]);break;
    case 'info':ring(12,12,9.5);P([[12,11],[12,17]]);dot(12,7.5,1.3);break;
    case 'settings':ring(12,12,3.5);ring(12,12,7.5);for(let i=0;i<8;i++){const a=i*Math.PI/4;P([[12+8*Math.cos(a),12+8*Math.sin(a)],[12+10.5*Math.cos(a),12+10.5*Math.sin(a)]]);}break;
    case 'oil':P([[3,10],[15,10],[19,7],[22,8],[17,14],[15,17],[5,17],[3,14],[3,10]]);P([[8,10],[8,7],[11,7]]);dot(21,15,1.4);break;
    case 'brake':ring(12,12,9.5);ring(12,12,3);P([[5,6],[2,9],[2,15],[5,18]]);break;
    case 'drop':P([[12,3],[6,12],[6,15],[8,19],[12,21],[16,19],[18,15],[18,12],[12,3]]);break;
    case 'filter':P([[3,6],[21,6],[21,18],[3,18],[3,6]]);for(let i=6;i<=18;i+=4)P([[i,6],[i,18]]);break;
    case 'fan':ring(12,12,2);P([[12,10],[10,4],[15,3],[13,10]]);P([[14,12],[20,10],[21,15],[14,14]]);P([[11,14],[9,20],[4,18],[10,13]]);break;
    case 'plug':P([[9,3],[9,8]]);P([[15,3],[15,8]]);P([[6,8],[18,8],[18,12],[15,16],[9,16],[6,12],[6,8]]);P([[12,16],[12,22]]);break;
    case 'check':ring(12,12,9.5);P([[7,12],[11,16],[17,8]]);break;
    case 'battery':P([[2,7],[19,7],[19,18],[2,18],[2,7]]);P([[21,10],[21,15]]);P([[6,10],[6,15]]);P([[10,10],[10,15]]);P([[14,10],[14,15]]);break;
    case 'road':P([[7,21],[10,3]]);P([[17,21],[14,3]]);P([[12,5],[12,8]]);P([[12,11],[12,14]]);P([[12,17],[12,20]]);break;
    case 'fuel':P([[4,21],[4,4],[14,4],[14,21]]);P([[2,21],[16,21]]);P([[6,7],[12,7],[12,11],[6,11],[6,7]]);P([[14,10],[18,10],[19,12],[19,17],[21,17],[21,8],[18,5]]);break;
    case 'ev':P([[8,3],[8,8]]);P([[16,3],[16,8]]);P([[5,8],[19,8],[19,12],[16,16],[8,16],[5,12],[5,8]]);P([[12,16],[12,21]]);break;
    case 'range':ring(6,15,3.5);P([[6,15],[6,15]]);P([[9,15],[13,15],[13,9],[17,9]]);ring(19,6,3);P([[19,9],[19,12]]);break;
    case 'chevron':P([[9,5],[16,12],[9,19]]);break;
    case 'left':P([[15,5],[8,12],[15,19]]);break;
    case 'scan':P([[3,8],[3,3],[8,3]]);P([[16,3],[21,3],[21,8]]);P([[21,16],[21,21],[16,21]]);P([[8,21],[3,21],[3,16]]);P([[6,12],[18,12]]);break;
    case 'car':P([[2,16],[2,12],[5,11],[8,7],[16,7],[19,11],[22,12],[22,16],[2,16]]);ring(7,17,2.2);ring(17,17,2.2);break;
    default:ring(12,12,9);
    }
}
module.exports={icon};
