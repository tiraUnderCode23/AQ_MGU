"""Bakes the seat pictures the app shows (OFF, and ON with the headrest logo lit) into app/src/seat_images.js:

    python packages/seatlights/app/tools/bake_images.py

From design/seat_off.png and design/seat_on.png (1122 x 1402, transparent background): the top of the seat
(the headrest, its badge and the top of the backrest), the ON picture moved by ALIGN so the two line up, the bottom
faded out, premultiplied RGBA (what the renderer's IMAGE takes), deflated and base64'd. The app inflates them with
Node's zlib and uploads each once (gpu.js picture()).
"""
import base64
import os
import zlib

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
DESIGN = os.path.join(HERE, "..", "..", "design")
OUT = os.path.join(HERE, "..", "src", "seat_images.js")
CROP = (90, 0, 820, 780)        # x0, y0, x1, y1 in the source pictures
ALIGN = (1, 1)                  # the ON picture moved right, down (px) onto the OFF one
FADE_FROM = 0.74                # the bottom from here (of the crop's height) fades out


def bake(name, shift):
    im = Image.open(os.path.join(DESIGN, name)).convert("RGBA")
    a = np.asarray(im)
    if shift != (0, 0):
        a = np.roll(np.roll(a, shift[1], 0), shift[0], 1)
    x0, y0, x1, y1 = CROP
    a = a[y0:y1, x0:x1].astype(np.float32)
    h = a.shape[0]
    f0 = int(h * FADE_FROM)
    k = np.ones(h, np.float32)
    k[f0:] = np.linspace(1, 0, h - f0) ** 1.4
    a[:, :, 3] *= k[:, None]
    alpha = a[:, :, 3:4] / 255.0
    rgb = a[:, :, :3] * alpha
    out = np.concatenate([rgb, a[:, :, 3:4]], 2).round().clip(0, 255).astype(np.uint8)
    return out.shape[1], out.shape[0], base64.b64encode(zlib.compress(out.tobytes(), 9)).decode("ascii")


def main():
    w, h, off = bake("seat_off.png", (0, 0))
    w2, h2, on = bake("seat_on.png", ALIGN)
    assert (w, h) == (w2, h2)
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("'use strict';\n/* generated by tools/bake_images.py from design/seat_off.png and seat_on.png; do not edit.\n")
        f.write(" * The top of the seat, OFF and ON (the logo lit): premultiplied RGBA, rows top-down, deflated, base64. */\n")
        f.write("module.exports = { w: %d, h: %d,\n    off: '%s',\n    on: '%s' };\n" % (w, h, off, on))
    print("wrote", OUT, os.path.getsize(OUT), "bytes,", w, "x", h)


if __name__ == "__main__":
    main()
