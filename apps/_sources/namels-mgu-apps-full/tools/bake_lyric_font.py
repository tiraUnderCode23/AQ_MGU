#!/usr/bin/env python3
"""Bake the glyph atlas for apps/cluster_lyrics (lyric_font_data.js).

The kit's own atlases only carry ASCII. Song text needs umlauts, accents and
Cyrillic, so this app ships its own alpha atlas baked from DejaVu Sans
(free licence, see apps/cluster_lyrics/DEJAVU_LICENSE.txt).

Usage: python3 tools/bake_lyric_font.py [font-dir]
Needs Pillow >= 9.2. The output is deterministic for a given font file.
"""
import base64
import json
import os
import sys
import zlib

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'apps', 'cluster_lyrics', 'lyric_font_data.js')
FONT_DIR = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/dejavu'
FACES = [('bold', 'DejaVuSans-Bold.ttf', 56), ('regular', 'DejaVuSans.ttf', 32)]
ATLAS_W = 1024
PAD = 1


def codepoints():
    cps = list(range(0x20, 0x7F)) + list(range(0xA0, 0x180)) + list(range(0x400, 0x460))
    cps += [0x2013, 0x2014, 0x2018, 0x2019, 0x201A, 0x201C, 0x201D, 0x201E, 0x2022, 0x2026,
            0x2039, 0x203A, 0x20AC, 0x266A, 0x266B]
    return [c for c in cps if c != 0xAD]


def bake(file, size):
    font = ImageFont.truetype(os.path.join(FONT_DIR, file), size)
    ascent, descent = font.getmetrics()
    glyphs, cells, x, y, row_h = {}, [], 0, 0, 0
    for cp in codepoints():
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        box = font.getbbox(ch, anchor='ls')
        gw, gh = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        if gw == 0 or gh == 0:
            glyphs[cp] = [0, 0, 0, 0, 0, 0, adv]
            continue
        if x + gw + PAD > ATLAS_W:
            x, y, row_h = 0, y + row_h + PAD, 0
        glyphs[cp] = [x, y, gw, gh, box[0], box[1], adv]
        cells.append((ch, x, y, box))
        x += gw + PAD
        row_h = max(row_h, gh)
    height = y + row_h + PAD
    atlas = Image.new('L', (ATLAS_W, height), 0)
    draw = ImageDraw.Draw(atlas)
    for ch, gx, gy, box in cells:
        draw.text((gx - box[0], gy - box[1]), ch, font=font, fill=255, anchor='ls')
    alpha = base64.b64encode(zlib.compress(atlas.tobytes(), 9)).decode('ascii')
    return {'size': size, 'ascent': ascent, 'descent': descent, 'atlasW': ATLAS_W, 'atlasH': height,
            'alpha': alpha, 'glyphs': glyphs}


def main():
    faces = {name: bake(file, size) for name, file, size in FACES}
    body = json.dumps(faces, separators=(',', ':'), sort_keys=True)
    with open(OUT, 'w', encoding='ascii', newline='\n') as out:
        out.write("'use strict';\n// Generated by tools/bake_lyric_font.py from DejaVu Sans. Do not edit.\n")
        out.write('module.exports = ' + body + ';\n')
    print('%s: %d KiB, %d glyphs per face' % (OUT, os.path.getsize(OUT) // 1024, len(codepoints())))


if __name__ == '__main__':
    main()
