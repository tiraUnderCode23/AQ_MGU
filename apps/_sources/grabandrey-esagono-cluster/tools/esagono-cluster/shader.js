/*
 * Esagono widget: the fragment shader cluster-render runs for the widget layer
 * (an `effect` layer, GLSL ES 1.00, `varying vec2 v_uv` with its origin top-left).
 * Everything is drawn procedurally: no textures, no uploads, a few uniforms a frame.
 *
 * Uniforms (set by esagono.js):
 *   u_size   vec2   the layer's size in pixels
 *   u_rpm    float  engine speed as a fraction of the scale (0..1)
 *   u_red    float  redline as a fraction of the scale
 *   u_divs   float  numerals on the scale (rpmMax / 1000)
 *   u_accent vec3   the drive mode's colour
 *   u_flash  float  1 while the shift flash is on
 *   u_num    vec3   big readout: whole digit, tenth digit, shown (1/0)
 *   u_mode   float  0 comfort, 1 sport, 2 track (the pips under the readout)
 *   u_bg     float  1 draws the dark backdrop behind the ring
 *
 * Works in Node (module.exports) and in a browser (window.ESAGONO_FS) so the
 * design/widget_preview.html harness compiles the exact same source.
 */
(function (root) {
    var FS = [
        'precision mediump float;',
        'varying vec2 v_uv;',
        'uniform vec2 u_size;',
        'uniform float u_rpm;',
        'uniform float u_red;',
        'uniform float u_divs;',
        'uniform vec3 u_accent;',
        'uniform float u_flash;',
        'uniform vec3 u_num;',
        'uniform float u_mode;',
        'uniform float u_bg;',
        '',
        'const float PI = 3.14159265;',
        'const float SEGS = 72.0;',
        'const vec3 RED = vec3(1.0, 0.16, 0.10);',
        'const vec3 ORANGE = vec3(1.0, 0.54, 0.0);',
        '',
        'float aa(float d, float w) { return 1.0 - smoothstep(-w, w, d); }',
        '',
        '/* a bar with pointed ends, centred on the origin, horizontal */',
        'float bar(vec2 q, float halfLen, float th) {',
        '    q = abs(q);',
        '    return max(q.y - th, q.x + q.y - halfLen);',
        '}',
        '',
        '/* hexagon with flat top and bottom; r is the apothem */',
        'float sdHex(vec2 p, float r) {',
        '    const vec3 k = vec3(-0.866025404, 0.5, 0.577350269);',
        '    p = abs(p);',
        '    p -= 2.0 * min(dot(k.xy, p), 0.0) * k.xy;',
        '    p -= vec2(clamp(p.x, -k.z * r, k.z * r), r);',
        '    return length(p) * sign(p.y);',
        '}',
        '',
        '/* seven-segment masks, bit 1 = a (top) ... bit 64 = g (middle) */',
        'float digitMask(float d) {',
        '    if (d < 0.5) return 63.0;',
        '    if (d < 1.5) return 6.0;',
        '    if (d < 2.5) return 91.0;',
        '    if (d < 3.5) return 79.0;',
        '    if (d < 4.5) return 102.0;',
        '    if (d < 5.5) return 109.0;',
        '    if (d < 6.5) return 125.0;',
        '    if (d < 7.5) return 7.0;',
        '    if (d < 8.5) return 127.0;',
        '    return 111.0;',
        '}',
        'float has(float m, float w) { return mod(floor(m / w + 0.001), 2.0); }',
        '',
        '/* an angular, slanted seven-segment digit in the box org..org+sz (pixels, y down) */',
        'float digit(vec2 p, vec2 org, vec2 sz, float d) {',
        '    vec2 q = p - org;',
        '    q.x -= (sz.y - q.y) * 0.12;',
        '    if (q.x < -sz.x * 0.3 || q.y < -sz.y * 0.2 || q.x > sz.x * 1.3 || q.y > sz.y * 1.2) return 0.0;',
        '    float m = digitMask(d);',
        '    float th = sz.x * 0.11;',
        '    float hl = sz.x * 0.5 - th * 0.35;',
        '    float vl = sz.y * 0.25 - th * 0.35;',
        '    float dist = 1e4;',
        '    if (has(m, 1.0) > 0.5)  dist = min(dist, bar(q - vec2(sz.x * 0.5, th), hl, th));',
        '    if (has(m, 2.0) > 0.5)  dist = min(dist, bar((q - vec2(sz.x - th, sz.y * 0.25 + th * 0.5)).yx, vl, th));',
        '    if (has(m, 4.0) > 0.5)  dist = min(dist, bar((q - vec2(sz.x - th, sz.y * 0.75 - th * 0.5)).yx, vl, th));',
        '    if (has(m, 8.0) > 0.5)  dist = min(dist, bar(q - vec2(sz.x * 0.5, sz.y - th), hl, th));',
        '    if (has(m, 16.0) > 0.5) dist = min(dist, bar((q - vec2(th, sz.y * 0.75 - th * 0.5)).yx, vl, th));',
        '    if (has(m, 32.0) > 0.5) dist = min(dist, bar((q - vec2(th, sz.y * 0.25 + th * 0.5)).yx, vl, th));',
        '    if (has(m, 64.0) > 0.5) dist = min(dist, bar(q - vec2(sz.x * 0.5, sz.y * 0.5), hl, th));',
        '    return aa(dist, 0.9);',
        '}',
        '',
        'void main() {',
        '    vec2 p = v_uv * u_size;',
        '    float R = min(u_size.x * 0.40, u_size.y * 0.44);',
        '    float s = R / 250.0;',
        '    vec2 C = vec2(u_size.x * 0.5, u_size.y * 0.53);',
        '    vec2 v = p - C;',
        '    float r = length(v);',
        '    vec3 col = vec3(0.0);',
        '    float a = 0.0;',
        '',
        '    if (u_bg > 0.5) {',
        '        col = vec3(0.016, 0.016, 0.024) + u_accent * 0.06 * smoothstep(R, 0.0, r);',
        '        a = smoothstep(R + 70.0 * s, R - 10.0 * s, r) * 0.94;',
        '    }',
        '',
        '    float ang = atan(v.y, v.x);',
        '    float t = mod(ang - 0.75 * PI + 4.0 * PI, 2.0 * PI) / (1.5 * PI);',
        '',
        '    if (t <= 1.0) {',
        '        /* the segmented rev ring */',
        '        float sidx = floor(t * SEGS);',
        '        float f = fract(t * SEGS);',
        '        float perK = SEGS / u_divs;',
        '        float major = mod(sidx, perK) < 0.5 ? 1.0 : 0.0;',
        '        float rin = R - (major > 0.5 ? 42.0 : 30.0) * s;',
        '        float arcLen = 1.5 * PI * r / SEGS;',
        '        float dAng = (0.5 - abs(f - 0.5)) * arcLen - 2.0 * s;',
        '        float dRad = min(r - rin, R - r);',
        '        float inside = aa(-min(dAng, dRad), 0.8);',
        '        float mid = (sidx + 0.5) / SEGS;',
        '        vec3 hot = mid >= u_red ? RED : (mid >= u_red - 1.5 / u_divs ? ORANGE : u_accent);',
        '        bool lit = mid < u_rpm;',
        '        vec3 segCol = lit ? hot : (mid >= u_red ? vec3(0.17, 0.05, 0.04) : vec3(0.09, 0.094, 0.11));',
        '        col = mix(col, segCol, inside); a = max(a, inside);',
        '        if (t < u_rpm) {',
        '            float gd = max(max(rin - r, r - R), 0.0);',
        '            float g = exp(-gd / (10.0 * s)) * 0.55 * (1.0 - inside);',
        '            col = mix(col, hot, g); a = max(a, g);',
        '        }',
        '',
        '        /* the outer ring, red past the redline */',
        '        float ro = abs(r - (R + 12.0 * s)) - 1.5 * s;',
        '        vec3 ringCol = t >= u_red ? RED : vec3(0.35);',
        '        float ri = aa(ro, 0.8);',
        '        col = mix(col, ringCol, ri); a = max(a, ri);',
        '',
        '        /* ticks every 500 rpm */',
        '        float tk = t * u_divs * 2.0;',
        '        float tf = abs(fract(tk + 0.5) - 0.5) * (1.5 * PI * r / (u_divs * 2.0));',
        '        float big = mod(floor(tk + 0.5), 2.0) < 0.5 ? 1.0 : 0.0;',
        '        float tr = r - (R + 20.0 * s);',
        '        float tlen = (big > 0.5 ? 18.0 : 10.0) * s;',
        '        float td = max(tf - (big > 0.5 ? 1.6 : 1.0) * s, max(-tr, tr - tlen));',
        '        float ti = aa(td, 0.8) * (big > 0.5 ? 1.0 : 0.45);',
        '        vec3 tc = t >= u_red - 0.001 ? RED : vec3(0.9);',
        '        col = mix(col, tc, ti); a = max(a, ti);',
        '    }',
        '',
        '    /* shift flash: the outer ring glows */',
        '    if (u_flash > 0.5) {',
        '        float fg = exp(-abs(r - (R + 12.0 * s)) / (7.0 * s)) * 0.9;',
        '        col = mix(col, vec3(1.0, 0.3, 0.2), fg); a = max(a, fg);',
        '    }',
        '',
        '    /* numerals round the ring */',
        '    vec2 nsz = vec2(18.0, 30.0) * s;',
        '    for (int i = 0; i <= 9; i++) {',
        '        float fi = float(i);',
        '        if (fi > u_divs + 0.1) break;',
        '        float na = 0.75 * PI + 1.5 * PI * fi / u_divs;',
        '        vec2 nc = C + vec2(cos(na), sin(na)) * (R - 68.0 * s);',
        '        if (abs(p.x - nc.x) > 30.0 * s || abs(p.y - nc.y) > 30.0 * s) continue;',
        '        float cov = digit(p, nc - nsz * 0.5, nsz, fi);',
        '        vec3 numCol = fi / u_divs >= u_red - 0.001 ? RED : vec3(0.86);',
        '        col = mix(col, numCol, cov); a = max(a, cov);',
        '    }',
        '',
        '    /* the centre hexagon */',
        '    vec2 hp = p - C - vec2(0.0, 6.0 * s);',
        '    float hd = sdHex(hp, 118.0 * s);',
        '    float hin = aa(hd, 0.8);',
        '    vec3 fill = mix(vec3(0.11, 0.11, 0.14), vec3(0.03, 0.03, 0.04), clamp(length(hp + vec2(0.0, 40.0 * s)) / (150.0 * s), 0.0, 1.0));',
        '    col = mix(col, fill, hin); a = max(a, hin);',
        '    float edge = max(aa(abs(hd) - 1.6 * s, 0.8), exp(-abs(hd) / (9.0 * s)) * 0.45);',
        '    col = mix(col, u_accent, edge); a = max(a, edge);',
        '',
        '    /* the big readout: rpm x 1000 with one decimal */',
        '    if (u_num.z > 0.5) {',
        '        vec2 dsz = vec2(58.0, 104.0) * s;',
        '        float gap = 26.0 * s;',
        '        vec2 o1 = vec2(C.x - (dsz.x * 2.0 + gap) * 0.5, C.y - 78.0 * s);',
        '        vec2 o2 = o1 + vec2(dsz.x + gap, 0.0);',
        '        float cv = max(digit(p, o1, dsz, u_num.x), digit(p, o2, dsz, u_num.y));',
        '        vec2 dp = p - vec2(o1.x + dsz.x + gap * 0.5 - 6.0 * s, o1.y + dsz.y - 8.0 * s);',
        '        cv = max(cv, aa(abs(dp.x) + abs(dp.y) - 8.0 * s, 0.8));',
        '        vec3 dc = u_flash > 0.5 ? vec3(1.0) : u_accent;',
        '        col = mix(col, dc, cv); a = max(a, cv);',
        '    }',
        '',
        '    /* divider and drive mode pips */',
        '    float ly = C.y + 50.0 * s;',
        '    float ld = max(abs(p.y - ly) - 1.0 * s, abs(p.x - C.x) - 78.0 * s);',
        '    float li = aa(ld, 0.8) * 0.6;',
        '    col = mix(col, u_accent, li); a = max(a, li);',
        '    for (int i = 0; i < 3; i++) {',
        '        float fi = float(i);',
        '        vec2 pc = vec2(C.x + (fi - 1.0) * 30.0 * s, ly + 26.0 * s);',
        '        float on = fi <= u_mode + 0.1 ? 1.0 : 0.18;',
        '        float pin = aa(sdHex((p - pc).yx, 8.0 * s), 0.8) * on;',
        '        col = mix(col, u_accent, pin); a = max(a, pin);',
        '    }',
        '',
        '    gl_FragColor = vec4(col, a);',
        '}'
    ].join('\n');

    if (typeof module !== 'undefined' && module.exports) module.exports = { FS: FS };
    else root.ESAGONO_FS = FS;
})(this);
